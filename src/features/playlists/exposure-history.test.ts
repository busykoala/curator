import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {config} from '@/config';
import {db} from '@/features/db/client';
import {createPlaylist} from './repository';
import {ownerRecordingExposure,rememberExposureFallback} from './exposure-history';
import {buildTrackEvidence} from './track-evidence';
const directory=mkdtempSync(join(tmpdir(),'curator-exposure-history-'));config.DATABASE_PATH=join(directory,'test.sqlite');
const database=db();database.exec("INSERT INTO curator_users(id,navidrome_user_id,username,display_name) VALUES(1,'one','one','One'),(2,'two','two','Two')");
const p=createPlaylist({name:'History',category:'mood',ownerUserId:1,config:{targetTracks:1}}),now=Date.now();
const evidence=buildTrackEvidence({artist:'Artist',title:'Song',tags:{},profile:{recordingTypes:['studio']}});
const verified=buildTrackEvidence({artist:'Artist',title:'Song',tags:{},profile:{recordingTypes:['studio']},external:[{field:'recordingId',value:'12345678-1234-1234-1234-123456789abc',scope:'recording',url:'https://musicbrainz.org/recording/12345678-1234-1234-1234-123456789abc'}]});
const live=buildTrackEvidence({artist:'Artist',title:'Song',tags:{},profile:{recordingTypes:['live']}});
test('recording history survives identity verification, file deletion and reimport while remaining owner-specific',()=>{
  database.exec("INSERT INTO files(id,path,album_key,artist_name,album_name,format,inode,link_count,size,mtime_ms,tags_json,properties_json,artwork_json,status) VALUES(1,'/music/song','album','Artist','Album','flac',1,1,1,1,'{\"title\":[\"Song\"]}','{}','{}','written')");
  const run=database.prepare("INSERT INTO playlist_runs(playlist_id,owner_user_id,status,preview,config_hash) VALUES(?,1,'complete',0,'test') RETURNING id").get(p.id) as {id:number};
  database.prepare('INSERT INTO playlist_exposure(owner_user_id,playlist_id,run_id,file_id,recording_key,exposed_at) VALUES(1,?,?,1,?,?)').run(p.id,run.id,evidence.recordingKey,now-1000);
  rememberExposureFallback(run.id,1,'Artist','Song',evidence);
  database.prepare('UPDATE playlist_exposure SET removed_at=? WHERE run_id=?').run(now,run.id);
  assert.deepEqual(ownerRecordingExposure(1,now)(1,'Artist','Song',verified),{exposure_count:1,removed_at:now});
  database.exec('DELETE FROM files WHERE id=1');
  assert.equal((database.prepare('SELECT count(*) n FROM playlist_exposure').get() as {n:number}).n,0);
  assert.deepEqual(ownerRecordingExposure(1,now)(999,'Artist','Song',verified),{exposure_count:1,removed_at:now});
  assert.deepEqual(ownerRecordingExposure(2,now)(999,'Artist','Song',verified),{exposure_count:0,removed_at:null});
  assert.deepEqual(ownerRecordingExposure(1,now)(999,'Artist','Song',live),{exposure_count:0,removed_at:null});
  database.exec('DELETE FROM playlist_runs;DELETE FROM smart_playlists;DELETE FROM curator_users WHERE id=1');
  assert.equal((database.prepare('SELECT count(*) n FROM playlist_recording_exposure').get() as {n:number}).n,0);
});
test.after(()=>{database.close();delete(globalThis as {curatorDb?:unknown}).curatorDb;rmSync(directory,{recursive:true,force:true})});
